import AppKit
import ApplicationServices
import Foundation

/// Types dictated text into whatever field has focus: put it on the clipboard, press ⌘V,
/// then put back what the user had on the clipboard. Needs Accessibility.
enum Paster {
    static func paste(_ text: String, restoreClipboard: Bool = true) -> Bool {
        guard AXIsProcessTrusted() else { return false }
        let pb = NSPasteboard.general
        // Password managers mark secrets as concealed/transient and clear them after a while.
        // Putting such an item back would give it a new life on the clipboard, so drop it instead.
        let sensitive: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        let items = pb.pasteboardItems ?? []
        let keep = !items.contains { item in item.types.contains { sensitive.contains($0.rawValue) } }
        let saved: [[NSPasteboard.PasteboardType: Data]] = (keep ? items : []).map { item in
            var d: [NSPasteboard.PasteboardType: Data] = [:]
            for t in item.types { if let v = item.data(forType: t) { d[t] = v } }
            return d
        }
        pb.clearContents()
        pb.setString(text, forType: .string)
        // Clipboard managers skip transient items, so dictations don't pile up in their history.
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        let ours = pb.changeCount

        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)

        if restoreClipboard {
            DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) {
                guard pb.changeCount == ours else { return }  // the user copied something meanwhile
                pb.clearContents()
                if saved.isEmpty { return }
                let items = saved.map { d -> NSPasteboardItem in
                    let item = NSPasteboardItem()
                    for (t, v) in d { item.setData(v, forType: t) }
                    return item
                }
                if !items.isEmpty { pb.writeObjects(items) }
            }
        }
        return true
    }

    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }
}
